! ARGUS - sonda del lector de ficheros .in de penhmain (subrutina PMRDR0).
!
! Se enlaza con PMRDR0, FWORD y el modulo PENHMAIN_input extraidos sin
! cambios del penhmain.f del usuario. Lee el .in por la entrada estandar
! (igual que penhmain), escribe los mensajes de la unidad 26 en fort26.txt
! y vuelca por la salida estandar el codigo de retorno y los valores leidos.
! No inicializa PENELOPE ni simula nada.

PROGRAM ARGUS_INPROBE
  USE PENHMAIN_input
  USE PENERROR_mod
  IMPLICIT NONE
  INTEGER :: I, J
  OPEN(26, FILE='fort26.txt')
  CALL PMRDR0
  CLOSE(26)
  WRITE(6,'(A,I8)') 'IRETRN ', IRETRN
  WRITE(6,'(A,A)') 'REASON ', TRIM(REASON)
  WRITE(6,'(A,A)') 'TITLE ', TRIM(TITLE_TITLE)
  WRITE(6,'(A,I8)') 'KPARP ', SKPAR_KPARP
  WRITE(6,'(A,A)') 'SRNUCL ', TRIM(SRNUCL_FNAME)
  WRITE(6,'(A,ES25.16)') 'SE0 ', SENERG_SE0
  WRITE(6,'(A,I8)') 'NISPEC ', NISPEC
  DO I = 1, NISPEC
    WRITE(6,'(A,2ES25.16)') 'SPECTR ', SPECTR_Ei(I), SPECTR_Pi(I)
  END DO
  WRITE(6,'(A,I8)') 'NLINE ', NLINE
  DO I = 1, NLINE
    WRITE(6,'(A,2ES25.16)') 'SLINES ', SLINES_Ei(I), SLINES_Pi(I)
  END DO
  WRITE(6,'(A,3ES25.16)') 'SGPOL ', SGPOL_SP1, SGPOL_SP2, SGPOL_SP3
  WRITE(6,'(A,3ES25.16)') 'SPOSIT ', SPOSIT_SX0, SPOSIT_SY0, SPOSIT_SZ0
  WRITE(6,'(A,3ES25.16)') 'SBOX ', SBOX_SSX, SBOX_SSY, SBOX_SSZ
  WRITE(6,'(A,I8)') 'NKBS ', NKBS
  DO I = 1, NKBS
    WRITE(6,'(A,I8,A,A4,A)') 'SBODY ', SBODY_KB(I), ' [', SBODY_KBW(I), ']'
  END DO
  WRITE(6,'(A,I3,3ES25.16)') 'SCONE ', ICONE, SCONE_THETA, SCONE_PHI, SCONE_ALPHA
  WRITE(6,'(A,I3,4ES25.16)') 'SRECTA ', IRECTA, SRECTA_THETAL, SRECTA_THETAU, SRECTA_PHIL, SRECTA_PHIU
  WRITE(6,'(A,I8)') 'NPSFI ', NPSFI
  DO I = 1, NPSFI
    WRITE(6,'(A,A)') 'IPSFN ', TRIM(IPSFN_FNAME(I))
  END DO
  WRITE(6,'(A,I8)') 'NMATER ', NMATER
  DO I = 1, MIN(NMATER, MAXMAT)
    WRITE(6,'(A,A)') 'MFNAME ', TRIM(MFNAME_FNAME(I))
    WRITE(6,'(A,7ES25.16)') 'MSIMPA ', (MSIMPA_EABS(J,I), J=1,3), MSIMPA_C1(I), MSIMPA_C2(I), &
      MSIMPA_WCC(I), MSIMPA_WCR(I)
  END DO
  WRITE(6,'(A,A)') 'GEOMFN ', TRIM(GEOMFN_FNAME)
  WRITE(6,'(A,I8)') 'NPARIN ', NPARIN
  DO I = 1, NPARIN
    WRITE(6,'(A,I8,ES25.16)') 'PARINP ', PARINP_IP(I), PARINP_PARINP(I)
  END DO
  WRITE(6,'(A,I8)') 'NKBG1 ', NKBG1
  DO I = 1, NKBG1
    WRITE(6,'(A,I8,A,A4,A,ES25.16)') 'DSMAX ', DSMAX_KB(I), ' [', DSMAX_KBW(I), '] ', DSMAX_DSMAX(I)
  END DO
  WRITE(6,'(A,I8)') 'NKBG2 ', NKBG2
  WRITE(6,'(A,I8)') 'NKBG3 ', NKBG3
  WRITE(6,'(A,I8)') 'NLE ', NLE
  WRITE(6,'(A,I8)') 'NLB ', NLB
  WRITE(6,'(A,I8)') 'NIFOR ', NIFOR
  WRITE(6,'(A,I8)') 'NBRS ', NBRS
  WRITE(6,'(A,I8)') 'NXRS ', NXRS
  WRITE(6,'(A,I8)') 'NIDET ', NIDET
  WRITE(6,'(A,I8)') 'NADET ', NADET
  WRITE(6,'(A,I8)') 'NEDET ', NEDET
  WRITE(6,'(A,2ES25.16,I8)') 'GRIDX ', GRIDX_XL, GRIDX_XU, GRIDX_NDBX
  WRITE(6,'(A,2ES25.16,I8)') 'GRIDY ', GRIDY_YL, GRIDY_YU, GRIDY_NDBY
  WRITE(6,'(A,2ES25.16,I8)') 'GRIDZ ', GRIDZ_ZL, GRIDZ_ZU, GRIDZ_NDBZ
  WRITE(6,'(A,ES25.16,I8)') 'GRIDR ', GRIDR_RU, GRIDR_NDBR
  WRITE(6,'(A,I8)') 'NEPROM ', NEPROM
  WRITE(6,'(A,A)') 'RESUME ', TRIM(RESUME_FNAME)
  WRITE(6,'(A,A)') 'DUMPTO ', TRIM(DUMPTO_FNAME)
  WRITE(6,'(A,ES25.16)') 'NSIMSH ', NSIMSH_DSHN
  WRITE(6,'(A,ES25.16)') 'TIME ', TIME_TIMEA
  WRITE(6,'(A,2I12)') 'RSEED ', RSEED_ISEED1, RSEED_ISEED2
  ! --- Resto del modulo PENHMAIN_input (secciones de los formularios de ARGUS) ---
  WRITE(6,'(A,I8)') 'IPSPLI ', IPSPLI_NSPLIT
  WRITE(6,'(A,2ES25.16)') 'WGTWIN ', WGTWIN_WGMIN, WGTWIN_WGMAX
  WRITE(6,'(A,2ES25.16)') 'EPMAX ', EPMAX_EPMAX, EPMAX_EHMAX
  DO I = 1, MIN(NMATER, MAXMAT)
    WRITE(6,'(A,6ES25.16)') 'MSIMPH ', (MSIMPH_EABSH(J,I), J=1,3), MSIMPH_C1H(I), MSIMPH_C2H(I), MSIMPH_WCCH(I)
    WRITE(6,'(A,2ES25.16)') 'MSIMPN ', MSIMPN_FNABS(I), MSIMPN_FORCEN(I)
  END DO
  DO I = 1, NKBG2
    WRITE(6,'(A,I8,A,A4,A,3ES25.16)') 'EABSB ', EABSB_KB(I), ' [', EABSB_KBW(I), '] ', (EABSB_EABSB(J,I), J=1,3)
  END DO
  DO I = 1, NKBG3
    WRITE(6,'(A,I8,A,A4,A,3ES25.16)') 'EABSBH ', EABSBH_KB(I), ' [', EABSBH_KBW(I), '] ', &
      (EABSBH_EABSBH(J,I), J=1,3)
  END DO
  WRITE(6,'(A,2ES25.16)') 'PFIELD ', EMFIELD_ULDE, EMFIELD_ULDV
  DO I = 1, NLE
    WRITE(6,'(A,I8,A,A4,A,3ES25.16)') 'EFIELD ', EMFIELD_KBE(I), ' [', EMFIELD_KBEW(I), '] ', (EMFIELD_E(J,I), J=1,3)
  END DO
  DO I = 1, NLB
    WRITE(6,'(A,I8,A,A4,A,3ES25.16)') 'BFIELD ', EMFIELD_KBB(I), ' [', EMFIELD_KBBW(I), '] ', (EMFIELD_B(J,I), J=1,3)
  END DO
  DO I = 1, NIFOR
    WRITE(6,'(A,I8,A,A4,A,2I8,3ES25.16)') 'IFORCE ', IFORCE_KB(I), ' [', IFORCE_KBW(I), '] ', IFORCE_KPAR(I), &
      IFORCE_ICOL(I), IFORCE_FORCER(I), IFORCE_WLOW(I), IFORCE_WHIGH(I)
  END DO
  DO I = 1, NBRS
    WRITE(6,'(A,I8,A,A4,A,I8)') 'IBRSPL ', IBRSPL_KB(I), ' [', IBRSPL_KBW(I), '] ', IBRSPL_IBRSPL(I)
  END DO
  DO I = 1, NXRS
    WRITE(6,'(A,I8,A,A4,A,I8)') 'IXRSPL ', IXRSPL_KB(I), ' [', IXRSPL_KBW(I), '] ', IXRSPL_IXRSPL(I)
  END DO
  WRITE(6,'(A,2ES25.16,I8)') 'NBE ', NBE_EL, NBE_EU, NBE_NBE
  WRITE(6,'(A,2I8)') 'NBANGL ', NBANGL_NBTH, NBANGL_NBPH
  DO I = 1, MIN(NIDET, MIDET)
    WRITE(6,'(A,2ES25.16,3I8)') 'IMPDET ', IMPDET_EL(I), IMPDET_EU(I), IMPDET_NBE(I), IMPDET_IPSF(I), IMPDET_IDCUT(I)
    WRITE(6,'(A,A)') 'IDSPC ', TRIM(IDSPC_FNAME(I))
    WRITE(6,'(A,A)') 'IDPSF ', TRIM(IDPSF_FNAME(I))
    WRITE(6,'(A,A)') 'IDFLNC ', TRIM(IDFLNC_FNAME(I))
    WRITE(6,'(A,2ES25.16,I8)') 'IDAGEL ', IDAGEL_AGEL(I), IDAGEL_AGEU(I), IDAGEL_NAGE(I)
    WRITE(6,'(A,A)') 'IDAGEF ', TRIM(IDAGEF_FNAME(I))
    DO J = 1, NKBID(I)
      WRITE(6,'(A,I3,I8,A,A4,A)') 'IDBODY ', I, IDBODY_KB(I,J), ' [', IDBODY_KBW(I,J), ']'
    END DO
    WRITE(6,'(A,I3,6I3)') 'IDKPAR ', I, (IDKPAR_KPAR(I,J), J=1,6)
  END DO
  DO I = 1, MIN(NADET, MADET)
    WRITE(6,'(A,4ES25.16)') 'ANGDET ', ANGDET_THETA1(I), ANGDET_THETA2(I), ANGDET_PHI1(I), ANGDET_PHI2(I)
    WRITE(6,'(A,2ES25.16,I8)') 'ADENER ', ADENER_EL(I), ADENER_EU(I), ADENER_NBE(I)
    WRITE(6,'(A,6I3)') 'ADKPAR ', (ADKPAR_KPAR(I,J), J=1,6)
    WRITE(6,'(A,A)') 'ADSPC ', TRIM(ADSPC_FNAME(I))
  END DO
  DO I = 1, MIN(NEDET, MEDET)
    WRITE(6,'(A,2ES25.16,I8)') 'ENDETC ', ENDETC_EL(I), ENDETC_EU(I), ENDETC_NBE(I)
    WRITE(6,'(A,A)') 'EDSPC ', TRIM(EDSPC_FNAME(I))
    DO J = 1, NKBED(I)
      WRITE(6,'(A,I3,I8,A,A4,A)') 'EDBODY ', I, EDBODY_KB(I,J), ' [', EDBODY_KBW(I,J), ']'
    END DO
  END DO
  DO I = 1, MIN(NEPROM, MAXMAT)
    WRITE(6,'(A,A)') 'EPROF ', TRIM(EPROF_FNAME(I))
    WRITE(6,'(A,2I8)') 'EPROPM ', EPROPM_KP(I), EPROPM_M(I)
  END DO
  WRITE(6,'(A,ES25.16)') 'DUMPP ', DUMPP_DUMPP
  WRITE(6,'(A,I8)') 'LTRACK ', LTRACK_NSHOW
END PROGRAM ARGUS_INPROBE
